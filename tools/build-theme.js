/* Generates theme-light.css from style.css + responsive.css.
 * Every neutral (grey/black/white) colour is remapped onto an ink/paper palette;
 * saturated accent colours are left alone. Re-run after changing colours:
 *   npm i --no-save postcss && node tools/build-theme.js
 */
const fs = require('fs'), path = require('path'), postcss = require('postcss');
const root = path.join(__dirname, '..');
const INK = [17, 17, 22], PAPER = [244, 242, 238];
const COLOR_PROPS = /^(--[\w-]+|color|background|background-color|background-image|border|border-(top|right|bottom|left)(-color)?|border-color|outline(-color)?|box-shadow|text-shadow|fill|stroke|filter|caret-color|text-decoration-color|-webkit-text-fill-color|-webkit-text-stroke(-color)?)$/;
const SHADOW_PROPS = /^(box-shadow|text-shadow|filter)$/;
const TOKEN = /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+\s*(?:,\s*[\d.]+\s*)?\)|\bwhite\b|\bblack\b/g;

function parse(tok) {
  if (tok === 'white') return [255, 255, 255, 1];
  if (tok === 'black') return [0, 0, 0, 1];
  if (tok[0] === '#') {
    let h = tok.slice(1); if (h.length === 3) h = h.split('').map(x => x + x).join('');
    const n = [0, 2, 4].map(i => parseInt(h.substr(i, 2), 16));
    return [...n, h.length === 8 ? parseInt(h.substr(6, 2), 16) / 255 : 1];
  }
  const p = tok.match(/[\d.]+/g).map(Number); return [p[0], p[1], p[2], p.length > 3 ? p[3] : 1];
}
function remap(tok, shadow) {
  const [r, g, b, a] = parse(tok);
  if ((Math.max(r, g, b) - Math.min(r, g, b)) / 255 > 0.22) return tok;      // keep accent colours
  const lum = (r + g + b) / 3 / 255;
  if (shadow) {                                                                // soft dark shadows on paper
    const k = lum < 0.5 ? [40, 40, 56, a * 0.22] : [INK[0], INK[1], INK[2], a * 0.4];
    return `rgba(${k[0]},${k[1]},${k[2]},${+k[3].toFixed(3)})`;
  }
  const o = INK.map((ink, i) => Math.round(ink + (PAPER[i] - ink) * (1 - lum)));
  return a >= 1 ? `rgb(${o.join(',')})` : `rgba(${o.join(',')},${+a.toFixed(3)})`;
}
const prefix = sel => sel.split(',').map(s => {
  s = s.trim();
  if (/data-theme/.test(s)) return null;
  if (s === ':root' || s === 'html') return 'html[data-theme="light"]';
  if (s.startsWith('html ')) return 'html[data-theme="light"] ' + s.slice(5);
  return 'html[data-theme="light"] ' + s;
}).filter(Boolean).join(', ');

let out = '/* AUTO-GENERATED by tools/build-theme.js — light theme. Do not edit by hand (edit EXTRAS in the script). */\n';
for (const file of ['style.css', 'responsive.css']) {
  const css = postcss.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  const emit = (rule) => {
    const decls = [];
    rule.each(d => {
      if (d.type !== 'decl' || !COLOR_PROPS.test(d.prop) || !TOKEN.test(d.value)) return; TOKEN.lastIndex = 0;
      const v = d.value.replace(TOKEN, t => remap(t, SHADOW_PROPS.test(d.prop)));
      if (v !== d.value) decls.push(`${d.prop}:${v}${d.important ? ' !important' : ''}`);
    });
    // `background` shorthand resets background-clip, so carry gradient-text clipping along
    if (decls.some(d => d.startsWith('background'))) rule.each(d => { if (d.type === 'decl' && /^(-webkit-)?background-clip$/.test(d.prop)) decls.push(`${d.prop}:${d.value}`); });
    const sel = prefix(rule.selector);
    return decls.length && sel ? `${sel}{${decls.join(';')}}` : '';
  };
  css.each(node => {
    if (node.type === 'rule') out += emit(node) + '\n';
    else if (node.type === 'atrule' && /^(media|supports)$/.test(node.name)) {
      let inner = ''; node.each(r => { if (r.type === 'rule') inner += emit(r); });
      if (inner) out += `@media ${node.params}{${inner}}\n`.replace('@media ' + node.params, `@${node.name} ${node.params}`);
    }
  });
}
const EXTRAS = `
html[data-theme="light"]{color-scheme:light}
html[data-theme="light"] body{background:#f4f2ee}
html[data-theme="light"] #canvas-container{display:none}

html[data-theme="light"] .arc-project-card,html[data-theme="light"] .achieve-flow-card{box-shadow:0 18px 40px rgba(30,30,50,.18)!important;border-color:rgba(17,17,22,.16)!important}
html[data-theme="light"] .achieve-flow-card.is-active{box-shadow:0 24px 55px rgba(30,30,50,.26)!important;border-color:rgba(17,17,22,.3)!important}
html[data-theme="light"] .hero-blazer-img{filter:drop-shadow(0 -6px 28px rgba(30,30,50,.25))}
html[data-theme="light"] .tech-icon{filter:none!important;opacity:.85}
html[data-theme="light"] [style*="color: #fff"],html[data-theme="light"] [style*="color:#fff"]{color:#111116!important}
html[data-theme="light"] [style*="#cbd5e1"]{color:#3b3b48!important}
html[data-theme="light"] ::selection{background:#6d7cff;color:#fff}
`;
fs.writeFileSync(path.join(root, 'theme-light.css'), out + EXTRAS);
console.log('theme-light.css', (out + EXTRAS).length, 'bytes');
